#pragma once
#include <stddef.h>
#include <stdint.h>

// 기기 마이크. 켜 두면 계속 받고, 컴퓨터가 듣는 동안에만 USB 로 넘긴다(usbdev::micPush).
//
// D37 마이크는 켠 뒤로 계속 받는다(컴퓨터가 열 때 시작하지 않는다).
//   이유: 컴퓨터가 마이크를 여는 순간부터 소리가 나가야 첫 낱말이 잘리지 않는다
//         (마이크 칩을 그때 켜면 0.1초쯤 걸린다).
//   비용: 쓰지 않을 때도 마이크 칩과 받는 태스크가 돈다(전력·CPU 는 화면에 비해 작다).
//         받은 소리는 컴퓨터가 가져가지 않으면 그 자리에서 버린다 — 기기 밖으로 나가지 않는다.
//   탈출구: 컴퓨터가 열고 닫을 때 M5.Mic 을 켜고 끄게 바꾼다.
namespace mic {

// 마이크를 켠다(속도·배율은 config.h).
bool begin();

// loop 에서 가끔 부른다. 마이크가 한동안 소리를 주지 않으면(받을 덩어리를 다시 맡기는 데 실패해
// 멎은 경우) 다시 맡긴다. 다시 맡겼으면 true(로그를 남기라고).
bool poll(uint32_t nowMs);
// 스피커가 소리를 내는 동안 마이크를 내렸다가(pause) 다시 올린다(resume). 둘은 같은 소리 통로(I2S)를 쓴다(D63).
void pause();
void resume();

// (개발판) 켜면 마이크 소리 대신 1씩 올라가는 숫자(0~15999)를 내보낸다. 맥에서 받은 숫자가
// 빠지거나 겹치지 않았는지 세어, USB 로 가는 길에서 표본을 잃지 않는지 확인한다(tools/check_mac.py ramp).
void setTestRamp(bool on);

// 가장 최근 덩어리(8ms)의 소리 크기(RMS, 0~32767). 컴퓨터의 입력 음량을 곱한 뒤의 값이다.
uint16_t level();
// 같은 덩어리의, 입력 음량을 곱하기 전의 크기(방의 소리 그대로).
uint16_t rawLevel();

}  // namespace mic
